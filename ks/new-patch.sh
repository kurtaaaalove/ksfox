#!/bin/bash
# Create patches/ks/zz-ks-NNN-<slug>.patch from changes made in the build tree (workflow: patches/ks/README.md).
#   ks/new-patch.sh begin             bring the ks stack in the tree up to date, snapshot it (shadow git, tag ks-base)
#   ks/new-patch.sh edit <path>...    copy tree files (path relative to the Firefox tree) to .ks-edit/<path> to edit
#                                     on the host; a path that does not exist yet becomes a new, empty file
#   ks/new-patch.sh <slug>            overlay .ks-edit/, `git diff ks-base` in the container, check it applies
#                                     cleanly, write the next zz-ks-NNN-<slug>.patch with a KS-* header, re-snapshot
#   KS_NUM=004 ks/new-patch.sh <slug> reuse a number (rework of patch 004; the old file is replaced)
# Edits can also be made inside the container (the tree is not writable from the host):
#   CFCMD='cd /work/camoufox/camoufox-<ver>-<rel> && sed -i ... path' ks/container/cfrun shell
set -euo pipefail
B=${B:-/home/kurt/camoufox-build}; REPO=${REPO:-$(cd "$(dirname "$0")/.." && pwd)}
CFRUN=${CFRUN:-$B/bin/cfrun}; export KS_TAG=${KS_TAG:-v156.0.1-beta.36}
TREE=$B/work/camoufox/camoufox-${KS_TAG#v}; OUT=$B/work/dist/ks-newpatch
cd "$REPO"
grep -qx '/.ks-edit/' .git/info/exclude 2>/dev/null || echo '/.ks-edit/' >> .git/info/exclude
cf() { CFCMD="/opt/ks/ks-build.sh $1" "$CFRUN" shell; }
case "${1:?usage: $0 begin | edit <path>... | <slug>}" in
  begin) cf snapshot ;;
  edit)
    shift; [ $# -gt 0 ] || { echo "edit: which file(s)?"; exit 2; }
    for f; do
      case "$f" in /*|*..*) echo "path must be relative to the Firefox tree: $f"; exit 2 ;; esac
      mkdir -p ".ks-edit/$(dirname "$f")"
      if [ -f "$TREE/$f" ]; then cp "$TREE/$f" ".ks-edit/$f"; else : > ".ks-edit/$f"; echo "(new file)"; fi
      chmod u+w ".ks-edit/$f"; echo "edit: $REPO/.ks-edit/$f"
    done ;;
  *)
    slug=$1
    [[ $slug =~ ^[a-z0-9][a-z0-9-]*$ ]] || { echo "slug must be lowercase-kebab: $slug"; exit 2; }
    last=$(ls patches/ks/ 2>/dev/null | sed -nE 's/^zz-ks-([0-9]{3})-.*\.patch$/\1/p' | sort -n | tail -1)
    num=${KS_NUM:-$(printf '%03d' $((10#${last:-0} + 1)))}
    [[ $num =~ ^[0-9]{3}$ ]] || { echo "KS_NUM must be 3 digits"; exit 2; }
    name=zz-ks-$num-$slug.patch
    t0=$(date +%s)
    cf newpatch || { echo "new-patch: container step failed (see above; nothing written)"; exit 1; }
    mkdir -p patches/ks
    for old in patches/ks/zz-ks-$num-*.patch; do [ -e "$old" ] && { echo "replacing $old"; rm -f "$old"; }; done
    {
      echo "KS-Patch: ${name%.patch}"
      echo "KS-Purpose: TODO one paragraph: what and why"
      echo "KS-Fingerprint: TODO none | fp.html fields this is meant to change (space separated)"
      echo "KS-Web-Visible: TODO no | how a web page could observe it"
      echo "KS-Verify: TODO how to check it (pipeline step / command)"
      sed -n 's#^diff --git a/\([^ ]*\) .*#KS-Touches: \1#p' "$OUT/new.patch"
      echo "# Optional, read by ks/pipeline.sh: KS-Bundle-Diff: omni.ja!<entry> | KS-Bundle-Marker: omni.ja!<entry> <text>"
      echo "#                                 | KS-Runtime-Check: <url> <text>"
      stack=$(paste -sd' ' "$B/work/camoufox/.ks-state/camoufox-${KS_TAG#v}/applied.list" 2>/dev/null || true)
      echo "# Generated by ks/new-patch.sh on $(date '+%F %T'), on top of: upstream ${KS_TAG} ${stack}"
      echo
      cat "$OUT/new.patch"
    } > "patches/ks/$name"
    rm -rf .ks-edit
    cf snapshot >/dev/null   # records the new patch as applied ("already in tree") and moves ks-base past it
    echo "wrote patches/ks/$name ($(grep -c '^diff --git' "patches/ks/$name") file(s), $(( $(date +%s) - t0 ))s)."
    echo "next: fill in the KS-* header, git add + commit on ks/main, then ks/pipeline.sh" ;;
esac
